#!/usr/bin/env python3
"""Generate website and Doxygen CSS from the palette embedded by Qt."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
PALETTE = ROOT / 'resources/app/palette.json'
OUTPUT = ROOT / 'webpage/theme/palette.css'
REQUIRED = set('ORANGE LORANGE BLUE GREEN VIOLET INTERNAL INK BACKGROUND SURFACE SURFACE_RAISED GRID GREY DISABLED SELECTED HOVER MENU_HOVER ERROR ERROR_HOVER ERROR_FILL SIGNAL_LOW ON_ACCENT ON_VIOLET'.split())


def load_palette(path=PALETTE):
    def unique_object(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f'Duplicate palette key: {key}')
            result[key] = value
        return result

    palette = json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=unique_object)
    if not isinstance(palette, dict) or set(palette) != {'light', 'dark'}:
        raise ValueError('Palette must contain exactly light and dark modes')
    for mode, tokens in palette.items():
        if not isinstance(tokens, dict) or not {'SILICON_' + key for key in REQUIRED} <= tokens.keys():
            raise ValueError(f'{mode}: missing required palette tokens')
        for key, value in tokens.items():
            if not re.fullmatch(r'SILICON_[A-Z][A-Z0-9_]*', key):
                raise ValueError(f'Invalid token name: {key}')
            if not isinstance(value, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', value):
                raise ValueError(f'{mode}.{key}: expected #RRGGBB')
    if palette['light'].keys() != palette['dark'].keys():
        raise ValueError('Light and dark token sets must match')
    return palette


def render(palette):
    aliases = {
        'magenta': 'var(--silicon-violet)', 'paper': 'var(--silicon-background)',
        'card': 'var(--silicon-surface)', 'muted': 'var(--silicon-surface-raised)',
        'text-soft': 'var(--silicon-grey)',
        'border': 'color-mix(in srgb, var(--silicon-ink) 14%, transparent)',
        'dots': 'color-mix(in srgb, var(--silicon-ink) 8%, transparent)',
    }
    lines = ['/* Generated by ci/theme/generate.py; edit palette.json instead. */']
    for mode in ('light', 'dark'):
        lines.append(':root, :root.light, :root.light-mode {' if mode == 'light'
                     else ':root.dark, :root.dark-mode {')
        lines.append(f'  color-scheme: {mode};')
        for name, value in sorted(palette[mode].items()):
            lines.append(f'  --{name.lower().replace("_", "-")}: {value.lower()};')
        lines.extend(f'  --silicon-{name}: {value};' for name, value in aliases.items())
        lines.append('}')
    return '\n'.join(lines) + '\n'


def generate(source=PALETTE, output=OUTPUT, check=False):
    css = render(load_palette(source))
    if check:
        if not output.is_file() or output.read_text(encoding='utf-8') != css:
            raise ValueError('Missing or stale palette.css; run python3 ci/theme/generate.py')
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(css, encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        generate(check=args.check)
    except (ValueError, OSError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
