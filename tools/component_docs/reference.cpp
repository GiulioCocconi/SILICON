std::string typeSlug(std::string_view type)
{
  // Encode rather than discard punctuation so distinct type identifiers cannot collide.
  constexpr char hex[] = "0123456789abcdef";
  std::string    result;
  for (const unsigned char c : type) {
    if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9'))
      result += static_cast<char>(c);
    else {
      result += '-';
      result += hex[c >> 4];
      result += hex[c & 15];
    }
  }
  if (result.empty())
    throw std::invalid_argument("Empty component type identifier");
  return result;
}

std::string categorySlug(core::ComponentCategory category)
{
  std::string result(core::componentCategoryName(category));
  for (auto& c : result) {
    if (c == ' ')
      c = '-';
    else if (c >= 'A' && c <= 'Z')
      c += 'a' - 'A';
  }
  return result;
}

std::vector<Reference> collectReferences(const core::ComponentRegistry& registry,
                                         const ui::GUIComponentFactory& factory)
{
  std::vector<Reference> result;
  std::set<std::string>  coveredTypes;
  for (const auto& guiType : factory.availableTypes()) {
    try {
      const auto& mapping   = factory.metadata(guiType);
      auto        graphical = factory.create(guiType);
      Reference   entry{.type    = mapping.coreType.empty() ? guiType : mapping.coreType,
                        .guiType = guiType};
      if (mapping.coreType.empty()) {
        entry.metadata = *mapping.graphicalMetadata;
        if (entry.metadata.ignoreDocumentation)
          continue;
        entry.properties = graphical->propertyDefinitions();
      } else {
        // Enforce the same unique mapping used when loading circuit components.
        factory.createForCoreType(mapping.coreType);
        if (!coveredTypes.insert(mapping.coreType).second)
          throw std::runtime_error("Duplicate core mapping");
        const auto schema = registry.describeType(mapping.coreType);
        entry.metadata    = schema.metadata;
        if (entry.metadata.ignoreDocumentation)
          continue;
        entry.properties  = schema.properties;
        const auto* logic = dynamic_cast<ui::GraphicalLogicComponent*>(graphical.get());
        if (!logic || !logic->getComponent()
            || logic->getComponent()->typeName() != mapping.coreType)
          throw std::runtime_error("Graphical component does not match core type");
        const auto description = logic->getComponent()->describe();
        entry.ports            = description.ports;
        for (const auto& port : entry.ports) {
          const auto& ports = port.direction == core::PortDirection::Input
                                  ? graphical->getInputPorts()
                                  : graphical->getOutputPorts();
          if (port.index >= ports.size() || ports[port.index]->getSize() != port.width)
            throw std::runtime_error("Graphical pin does not match introspection: "
                                     + port.name);
          entry.portLabels.push_back(ports[port.index]->getName().toStdString());
        }
        if (entry.ports.size()
            != graphical->getInputPorts().size() + graphical->getOutputPorts().size())
          throw std::runtime_error("Graphical pin count does not match introspection");
        std::set<std::string> configurationIds;
        for (auto configuration : logic->getComponent()->documentationConfigurations()) {
          if (!configurationIds.insert(typeSlug(configuration.id)).second)
            throw std::runtime_error("Duplicate configuration ID: " + configuration.id);
          const auto example =
              configuredComponent(entry, factory, configuration.properties);
          entry.configurations.push_back(
              {std::move(configuration), previewSize(*example)});
        }
      }
      entry.previewSize = previewSize(*graphical);
      result.push_back(std::move(entry));
    } catch (const std::exception& error) {
      throw std::runtime_error(guiType + ": " + error.what());
    }
  }
  for (const auto& type : registry.availableTypes())
    if (!coveredTypes.contains(type))
      throw std::runtime_error("No graphical component registered for core type: "
                               + type);
  std::ranges::sort(result, [](const Reference& a, const Reference& b) {
    if (a.metadata.category != b.metadata.category)
      return a.metadata.category < b.metadata.category;
    if (a.metadata.displayName != b.metadata.displayName)
      return a.metadata.displayName < b.metadata.displayName;
    return a.type < b.type;
  });
  return result;
}

std::string componentPage(const Reference& reference)
{
  const auto         slug = typeSlug(reference.type);
  std::ostringstream page;
  const auto         images = [&](const std::string& imageSlug, std::string_view title,
                          const QSize& size) {
    for (const auto* theme : {"light", "dark"}) {
      page << "<img class=\"component-preview " << theme << "-only\" src=\"./"
           << imageSlug << "-" << theme << ".png\"";
      if (size.isValid())
        page << " width=\"" << size.width() << "\" height=\"" << size.height() << "\"";
      page << " alt=\"" << escaped(title) << "\">\n\n";
    }
  };
  page << Preamble << "# " << escaped(reference.metadata.displayName) << "\n\n"
       << "[Component Reference](../index.md) / ["
       << escaped(core::componentCategoryName(reference.metadata.category))
       << "](./index.md)\n\n"
       << escaped(reference.metadata.description) << "\n\nType: " << code(reference.type)
       << "\n\n"
       << "## Default configuration\n\n";
  images(slug, reference.metadata.displayName + " with ports", reference.previewSize);
  page
      << "The diagram and pin table show the default configuration placed in the editor. "
         "Changing properties can change the shape, pin count, or bus widths.\n\n";
  if (!reference.configurations.empty()) {
    page << "## Configuration examples\n\n"
            "Each example starts from the default configuration and applies the "
            "property values listed below.\n\n";
    for (const auto& configuration : reference.configurations) {
      page << "### " << escaped(configuration.title) << "\n\n"
           << escaped(configuration.description) << "\n\n";
      images(slug + "-configuration-" + typeSlug(configuration.id),
             reference.metadata.displayName + ": " + configuration.title,
             configuration.previewSize);
      page << "| Property | Value |\n| --- | --- |\n";
      const std::map ordered(configuration.properties.begin(),
                             configuration.properties.end());
      for (const auto& [key, value] : ordered)
        page << "| " << code(key) << " | " << code(formattedValue(value)) << " |\n";
      page << "\n";
    }
  }
  page << "## Pins\n\n";
  if (!reference.configurations.empty())
    page << "The following pins belong to the default configuration.\n\n";
  if (reference.ports.empty()) {
    page << "This component has no pins.\n\n";
  } else {
    bool aliases = false;
    for (std::size_t i = 0; i < reference.portLabels.size(); ++i)
      aliases = aliases || reference.portLabels[i] != reference.ports.at(i).name;
    page << "| Name | " << (aliases ? "Editor label | " : "")
         << "Direction | Width (bits) | Description |\n"
         << "| --- | " << (aliases ? "--- | " : "") << "--- | --- | --- |\n";
    for (std::size_t i = 0; i < reference.ports.size(); ++i) {
      const auto& port = reference.ports[i];
      page << "| " << code(port.name) << " | ";
      if (aliases)
        page << (reference.portLabels.at(i).empty() ? "Unlabeled"
                                                    : code(reference.portLabels[i]))
             << " | ";
      page << (port.direction == core::PortDirection::Input ? "Input" : "Output") << " | "
           << port.width << " | " << escaped(port.description) << " |\n";
    }
    page << "\n";
  }
  page << "## Properties\n\n"
          "Editable properties are listed, including those available only in "
          "other configurations.\n\n";
  if (std::ranges::none_of(reference.properties, [](const auto& property) {
        return property.access == core::PropertyAccess::Editable;
      }))
    page << "This component has no editable properties.\n";
  for (const auto& property : reference.properties) {
    if (property.access != core::PropertyAccess::Editable)
      continue;
    page << "### " << escaped(property.label) << " {#property-" << typeSlug(property.key)
         << "}\n\n"
         << escaped(property.description) << "\n\n| Attribute | Value |\n| --- | --- |\n"
         << "| Key | " << code(property.key) << " |\n"
         << "| Type | " << typeName(property.type) << " |\n"
         << "| Declared default | "
         << (property.defaultValue ? code(formattedValue(*property.defaultValue))
                                   : "No declared default")
         << " |\n";
    page << "| Accepted values | ";
    if (property.acceptedValues.empty())
      page << "Any value satisfying the constraints";
    for (std::size_t i = 0; i < property.acceptedValues.size(); ++i)
      page << (i ? ", " : "") << code(formattedValue(property.acceptedValues[i]));
    page << " |\n";
    if (property.constraints.minimum)
      page << "| Minimum (inclusive) | " << *property.constraints.minimum << " |\n";
    if (property.constraints.maximum)
      page << "| Maximum (inclusive) | " << *property.constraints.maximum << " |\n";
    if (property.constraints.normalization == core::PropertyNormalization::Clamp)
      page << "| Out-of-range behavior | Clamp to bounds |\n";
    page << "| Additional constraints | "
         << (property.constraints.description.empty()
                 ? "None"
                 : escaped(property.constraints.description))
         << " |\n| Availability | "
         << (property.availability.empty() ? "Always" : escaped(property.availability))
         << " |\n\n";
  }
  return page.str();
}

void generateReference(const std::filesystem::path&   output,
                       const core::ComponentRegistry& registry,
                       const ui::GUIComponentFactory& factory, QApplication& app)
{
  const auto     destination = std::filesystem::absolute(output);
  constexpr auto marker      = ".silicon-component-reference";
  if (std::filesystem::exists(destination)
      && (!std::filesystem::is_directory(destination)
          || (!std::filesystem::is_empty(destination)
              && !std::filesystem::is_regular_file(destination / marker))))
    throw std::runtime_error(
        "Refusing to replace a directory not generated by component_docs: "
        + destination.string());
  const auto references = collectReferences(registry, factory);
  // Generate before replacing the previous reference so a failure preserves it.
  std::filesystem::create_directories(destination.parent_path());
  QTemporaryDir temporary(QString::fromStdString(destination.string() + ".tmp-XXXXXX"));
  if (!temporary.isValid())
    throw std::runtime_error("Cannot create reference staging directory");
  const std::filesystem::path staging(temporary.path().toStdString());
  const auto                  originalTheme = ui::ThemeEngine::mode();
  try {
    std::map<core::ComponentCategory, std::vector<const Reference*>> categories;
    std::set<std::filesystem::path>                                  paths;
    for (const auto& reference : references) {
      const auto relative =
          std::filesystem::path(categorySlug(reference.metadata.category))
          / typeSlug(reference.type);
      if (!paths.insert(relative).second)
        throw std::runtime_error("Duplicate reference URL: " + relative.string());
      categories[reference.metadata.category].push_back(&reference);
      std::filesystem::create_directories(staging / relative.parent_path());
      writeFile(staging / (relative.string() + ".md"), componentPage(reference));
      for (const auto mode : {ui::theme::Mode::Light, ui::theme::Mode::Dark}) {
        ui::ThemeEngine::apply(app, mode);
        renderPng(reference, factory,
                  staging
                      / (relative.string()
                         + (mode == ui::theme::Mode::Light ? "-light.png" : "-dark.png")),
                  {});
        for (const auto& configuration : reference.configurations)
          renderPng(
              reference, factory,
              staging
                  / (relative.string() + "-configuration-" + typeSlug(configuration.id)
                     + (mode == ui::theme::Mode::Light ? "-light.png" : "-dark.png")),
              configuration.properties);
      }
    }
    std::ostringstream index;
    index << Preamble
          << "# Component Reference\n\n"
             "Browse the built-in component catalog by category. This reference is "
             "generated from SILICON's component registry and property schemas.\n\n";
    for (const auto& [category, entries] : categories) {
      const auto categoryName = escaped(core::componentCategoryName(category));
      const auto slug         = categorySlug(category);
      index << "- [" << categoryName << "](./" << slug << "/index.md) (" << entries.size()
            << ")\n";
      std::ostringstream list;
      list << Preamble << "# " << categoryName << "\n\n"
           << "[All categories](../index.md)\n\n"
           << "| Component | Description |\n| --- | --- |\n";
      for (const auto* entry : entries)
        list << "| [" << escaped(entry->metadata.displayName) << "](./"
             << typeSlug(entry->type) << ".md) | " << escaped(entry->metadata.description)
             << " |\n";
      writeFile(staging / slug / "index.md", list.str());
    }
    writeFile(staging / "index.md", index.str());
    writeFile(staging / marker, "Generated by SILICON component_docs.\n");
    ui::ThemeEngine::apply(app, originalTheme);
    std::filesystem::remove_all(destination);
    std::filesystem::rename(staging, destination);
  } catch (...) {
    ui::ThemeEngine::apply(app, originalTheme);
    throw;
  }
}

