  constexpr std::string_view Preamble =
      "---\neditLink: false\n---\n\n"
      "<!-- Generated by the component_docs CMake target. Do not edit. -->\n\n";

  // Metadata is plain text, never Markdown, HTML, or a Vue expression.
  std::string escaped(std::string_view value)
  {
    std::string result;
    for (const unsigned char c : value) {
      switch (c) {
        case '&': result += "&amp;"; break;
        case '<': result += "&lt;"; break;
        case '>': result += "&gt;"; break;
        case '"': result += "&quot;"; break;
        case '\'': result += "&#39;"; break;
        case '\n': result += "<br>"; break;
        case '\r': break;
        case '|':
        case '`':
        case '*':
        case '_':
        case '[':
        case ']':
        case '\\':
        case '{':
        case '}':
        case '$':
        case '#':
        case '!': result += "&#" + std::to_string(c) + ";"; break;
        default: result += static_cast<char>(c); break;
      }
    }
    return result;
  }

  std::string code(std::string_view value)
  {
    return "<code v-pre>" + escaped(value) + "</code>";
  }

  std::string formattedValue(const PropertyValue& value)
  {
    return std::visit(
        [](const auto& item) -> std::string {
          using T = std::decay_t<decltype(item)>;
          if constexpr (std::is_same_v<T, bool>)
            return item ? "true" : "false";
          else if constexpr (std::is_same_v<T, int>)
            return std::to_string(item);
          else if constexpr (std::is_same_v<T, std::string>)
            return item.empty() ? "\"\" (empty string)" : item;
          else {
            if (item.empty())
              return "[] (empty bus value)";
            std::string bits;
            for (auto it = item.rbegin(); it != item.rend(); ++it)
              bits += static_cast<char>(*it);
            return "0b" + bits;
          }
        },
        value);
  }

  std::string_view typeName(PropertyType type)
  {
    switch (type) {
      case PropertyType::Integer: return "Integer";
      case PropertyType::Boolean: return "Boolean";
      case PropertyType::String: return "String";
      case PropertyType::BusValue: return "Bus value";
    }
    throw std::logic_error("Unknown property type");
  }

  void writeFile(const std::filesystem::path& path, std::string_view contents)
  {
    std::ofstream file;
    file.exceptions(std::ios::failbit | std::ios::badbit);
    file.open(path, std::ios::binary);
    file.write(contents.data(), static_cast<std::streamsize>(contents.size()));
    file.close();
  }

  QRectF previewBounds(const ui::GraphicalComponent& component)
  {
    const auto bounds =
        component.sceneBoundingRect()
            .united(component.mapRectToScene(component.childrenBoundingRect()))
            .adjusted(-12, -12, 12, 12);
    if (!bounds.isValid() || !std::isfinite(bounds.width())
        || !std::isfinite(bounds.height()))
      throw std::runtime_error("Invalid preview bounds for " + component.getTypeName());
    return bounds;
  }

  QSize previewSize(const ui::GraphicalComponent& component)
  {
    const auto bounds = previewBounds(component);
    // Editor coordinates make pin labels too small on a documentation page.
    return QSize(static_cast<int>(std::ceil(bounds.width() * 2)),
                 static_cast<int>(std::ceil(bounds.height() * 2)));
  }

  std::unique_ptr<ui::GraphicalComponent>
  configuredComponent(const Reference& reference, const ui::GUIComponentFactory& factory,
                      const core::PropertyMap& properties)
  {
    auto component = factory.create(reference.guiType);
    if (!properties.empty())
      component->applyProperties(properties);
    return component;
  }

  void renderPng(const Reference& reference, const ui::GUIComponentFactory& factory,
                 const std::filesystem::path& path, const core::PropertyMap& properties)
  {
    auto           component = configuredComponent(reference, factory, properties);
    const QRectF   bounds    = previewBounds(*component);
    QGraphicsScene scene;
    scene.setFont(QApplication::font());
    scene.setItemIndexMethod(QGraphicsScene::NoIndex);
    scene.addItem(component.release());  // The scene owns the component and its children.
    for (auto* item : scene.items())
      item->setCacheMode(QGraphicsItem::NoCache);
    // Render directly at high resolution so bundled fonts and editor icons retain
    // their appearance, with at least four image pixels per displayed CSS pixel.
    const qreal scale =
        std::ceil(std::max(8.0, 1920.0 / std::max(bounds.width(), bounds.height())));
    QImage image(QSize(static_cast<int>(std::ceil(bounds.width() * scale)),
                       static_cast<int>(std::ceil(bounds.height() * scale))),
                 QImage::Format_ARGB32_Premultiplied);
    if (image.isNull())
      throw std::runtime_error("Cannot allocate PNG preview for " + reference.type);
    image.fill(Qt::transparent);
    QPainter painter;
    if (!painter.begin(&image))
      throw std::runtime_error("Cannot render PNG for " + reference.type);
    painter.setRenderHints(QPainter::Antialiasing | QPainter::TextAntialiasing
                           | QPainter::SmoothPixmapTransform);
    painter.setFont(QApplication::font());
    painter.scale(scale, scale);
    scene.render(&painter, QRectF(QPointF(0, 0), bounds.size()), bounds);
    if (!painter.end())
      throw std::runtime_error("Cannot finish PNG for " + reference.type);
    if (!image.save(QString::fromStdString(path.string()), "PNG"))
      throw std::runtime_error("Cannot save PNG preview for " + reference.type);
  }

